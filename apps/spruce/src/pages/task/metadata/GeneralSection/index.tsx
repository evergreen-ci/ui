import { StyledRouterLink } from "@evg-ui/lib/components/styles";
import { useTaskAnalytics } from "analytics";
import { CopyableID } from "components/CopyableID";
import {
  MetadataItem,
  MetadataSection,
  ProjectMetadata,
} from "components/MetadataCard";
import { RevisionLink } from "components/RevisionLink";
import { getTaskRoute } from "constants/routes";
import { TaskQuery } from "gql/generated/types";
import { getDisplayRevision } from "utils/string";
import { CompletedBy } from "./CompletedBy";
import { TaskOwnership } from "./TaskOwnership";

type Task = NonNullable<TaskQuery["task"]>;

interface GeneralSectionProps {
  task: Task;
}

export const GeneralSection: React.FC<GeneralSectionProps> = ({ task }) => {
  const taskAnalytics = useTaskAnalytics();

  const {
    baseTask,
    completedBy,
    displayTask,
    execution,
    generatedBy,
    generatedByName,
    project,
    versionMetadata,
  } = task;

  const { isPatch, user } = versionMetadata ?? {};

  return (
    <MetadataSection>
      <CopyableID textToCopy={task.id} tooltipLabel="Copy task ID" />

      {project && (
        <ProjectMetadata
          handleClick={() =>
            taskAnalytics.sendEvent({
              name: "Clicked metadata link",
              "link.type": "project link",
            })
          }
          {...project}
        />
      )}

      <MetadataItem label="Submitted by">{user.userId}</MetadataItem>
      {generatedBy && (
        <MetadataItem label="Generated by">
          <StyledRouterLink to={getTaskRoute(generatedBy)}>
            {generatedByName}
          </StyledRouterLink>
        </MetadataItem>
      )}
      {completedBy && <CompletedBy completedBy={completedBy} />}
      <TaskOwnership execution={execution} taskId={task.id} />
      {displayTask && (
        <MetadataItem label="Display task">
          <StyledRouterLink
            onClick={() =>
              taskAnalytics.sendEvent({
                name: "Clicked metadata link",
                "link.type": "display task link",
              })
            }
            to={getTaskRoute(displayTask.id, {
              execution: displayTask.execution,
            })}
          >
            {displayTask.displayName}
          </StyledRouterLink>
        </MetadataItem>
      )}
      {baseTask && (
        <MetadataItem label={isPatch ? "Base task" : "Previous task"}>
          <RevisionLink
            onClick={() =>
              taskAnalytics.sendEvent({
                name: "Clicked metadata link",
                "link.type": "base commit",
              })
            }
            revision={
              baseTask.versionMetadata
                ? getDisplayRevision(baseTask.versionMetadata)
                : ""
            }
            to={getTaskRoute(baseTask.id, { execution: baseTask.execution })}
          />
        </MetadataItem>
      )}
    </MetadataSection>
  );
};
